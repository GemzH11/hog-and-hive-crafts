package uk.co.hogandhivecrafts.backend.model;

/**
 * Enum representing the different types of crafts that patterns can be associated with.
 *
 * <p>Enum constant names form the public API contract (for example {@code KNITTING}).
 * Presentation-friendly labels should be handled in the UI layer.
 */
public enum CraftType {
  KNITTING,
  CROCHET,
  SEWING,
  EMBROIDERY,
  CROSS_STITCH,
  QUILTING,
  FELTING,
  MACRAME,
  OTHER
}
